// Split one CSV line into cells, honoring "double quotes" -- unlike the
// hand-edited files above, event names DO contain commas (e.g. "Sophomore
// Retreat (No Classes: Fr, Jr, & Sr)"), and Python's csv module quotes them.
function splitCsvLine(line) {
  const cells = [];
  let cell = "", inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"' && line[i + 1] === '"') { cell += '"'; i++; }  // "" = a literal quote
      else if (ch === '"') inQuotes = false;
      else cell += ch;
    } else if (ch === '"') inQuotes = true;
    else if (ch === ",") { cells.push(cell); cell = ""; }
    else cell += ch;
  }
  cells.push(cell);
  return cells.map((c) => c.trim());
}

// columns: date,end_date,time,name -- end_date only for multi-day events
// (inclusive), time ("HH:MM", 24-hour) empty for all-day ones.
function parseEventsCsv(text) {
  const events = [];
  for (const line of csvRows(text)) {
    const [date, endDate, time, name] = splitCsvLine(line);
    if (!date || !name) continue;
    events.push({ date, endDate: endDate || date, time: time || "", name });
  }
  events.sort((a, b) => (a.date + a.time).localeCompare(b.date + b.time));
  return events;
}

// "13:45" -> "1:45 p.m." (AP style, like the rest of SLUH's writing)
function formatEventTime(hhmm) {
  if (!hhmm) return "";
  let [h, m] = hhmm.split(":").map(Number);
  const ampm = h >= 12 ? "p.m." : "a.m.";
  h = h % 12 || 12;
  return m ? `${h}:${String(m).padStart(2, "0")} ${ampm}` : `${h} ${ampm}`;
}

// "Thu" / "Nov 12" pieces for the calendar's date column
function weekdayShort(dateStr) {
  const { y, m, d } = parseDate(dateStr);
  return new Date(Date.UTC(y, m - 1, d)).toLocaleDateString("en-US", { weekday: "short", timeZone: "UTC" });
}
function monthDay(dateStr) {
  const { y, m, d } = parseDate(dateStr);
  return new Date(Date.UTC(y, m - 1, d)).toLocaleDateString("en-US", { month: "short", day: "numeric", timeZone: "UTC" });
}

// ---- today's schedule as "segments" (periods + whole-school blocks) ----
// The timer used to know only class periods, so Studium, Activity Period and
// Advisory looked like long gaps ("Next: Period C in 52:00"). data.js now
// carries those as each day's "blocks" list, so everything the timer shows
// works from this one time-ordered list instead:
//   { key, kind: "period" | "block", title, start, end }   (minutes after midnight)
// A period split by lunch wave becomes two segments, Fr/So and Jr/Sr, since
// their windows overlap and the office tracks both. Blocks never overlap
// periods in the data (checked when this was written).
function daySegments(day) {
  if (!day) return [];
  const segments = [];
  for (const p of day.periods) {
    if (p.jrsrStartMinutes != null) {
      segments.push({ key: `${p.label}:frso`, kind: "period", title: `Period ${p.label} (Fr/So)`, start: p.startMinutes, end: p.endMinutes });
      segments.push({ key: `${p.label}:jrsr`, kind: "period", title: `Period ${p.label} (Jr/Sr)`, start: p.jrsrStartMinutes, end: p.jrsrEndMinutes });
    } else {
      segments.push({ key: p.label, kind: "period", title: `Period ${p.label}`, start: p.startMinutes, end: p.endMinutes });
    }
  }
  for (const b of day.blocks || []) {
    // "Advisory Period" reads better on the wall as just "Advisory"
    const title = b.name.replace(/^Advisory Period$/, "Advisory");
    segments.push({ key: `block:${b.name}:${b.startMinutes}`, kind: "block", title, start: b.startMinutes, end: b.endMinutes });
  }
  // by start time; at a tie (the two lunch waves of one period never tie, but
  // be safe) the order above is kept
  return segments.sort((a, b) => a.start - b.start);
}

function segmentIsLive(seg, now) {
  return now.minutes >= seg.start && now.minutes < seg.end;
}

// 0..1, by the second (not just the minute), so the bar moves smoothly
function segmentProgress(seg, now) {
  const nowSec = now.minutes * 60 + now.seconds;
  const startSec = seg.start * 60, endSec = seg.end * 60;
  if (nowSec <= startSec) return 0;
  if (nowSec >= endSec) return 1;
  return (nowSec - startSec) / (endSec - startSec);
}

