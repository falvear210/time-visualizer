//   - three columns: birthdays | timers | school calendar, with bigger type
//   - the timer counts Studium, Activity Period, Advisory, etc. (data.js's
//     per-day "blocks") as real parts of the day, not as gaps between classes
//   - the right column lists important school-wide dates from
